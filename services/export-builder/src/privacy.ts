/**
 * Two things must never leave in an export: who reviewed something, and what we
 * wrote down internally about a source.
 *
 * REVIEWER IDENTITY. `@data-foundry/query-model` states the guarantee — "the
 * REVIEWER IDENTITY is never projected onto any of these shapes" — and ships
 * `assertNoReviewerIdentity` as the control. This module applies that control at
 * the export boundary, and widens the reviewer set while doing it.
 *
 * The widening is the point. `canonicalFacts` checks a correction's reason
 * against the reviewer of THAT correction, which is the only reviewer it has in
 * hand at that moment. An export knows the whole compiled policy, so it checks
 * every reason against EVERY reviewer the policy declares. A reason reading
 * "corrected by j.okafor after a supplier call", attached to an override whose
 * declared reviewer is m.chen, passes the query layer and is caught here. It is
 * the same control with a bigger haystack, not a second implementation:
 * `assertNoReviewerIdentity` is imported rather than reimplemented, so the two
 * agree about what an identity looks like by construction.
 *
 * TWO STRENGTHS, ON PURPOSE. The query-model control matches derived tokens —
 * `legal@example.com` also matches a bare `legal`. That net is right for a
 * human-authored sentence and wrong for machine-generated bytes, where a
 * manifest field literally named `requires_legal_review` would trip it and
 * refuse a perfectly clean export. So authored prose (correction reasons) gets
 * the derived-token net, and the whole-artifact sweep matches the full declared
 * identity only. Both refuse; neither guesses. The sweep takes one more bound
 * from upstream — `MIN_IDENTITY_FRAGMENT`, the floor `reviewerIdentityTokens`
 * already applies to a derived token — because its haystack is a whole file of
 * model numbers, and a needle short enough to sit inside one is not evidence of
 * a person.
 *
 * INTERNAL NOTES. A `SourceRegistryEntry` carries text that exists for us and
 * not for a customer: `notes`, `geographic_notes`, the acquisition approver, the
 * licence-text file path, the rights reviewer. The manifest builder copies
 * fields onto an allow-list basis rather than spreading the entry, so none of it
 * travels — and `assertNoInternalText` checks the SERIALIZED BYTES rather than
 * the object, because a field-by-field check is only ever as good as the list of
 * fields somebody remembered to write down.
 */
import {
  MIN_IDENTITY_FRAGMENT,
  ReviewerIdentityLeak,
  assertNoReviewerIdentity,
  correctionFields,
  type CanonicalFactView,
} from '@data-foundry/query-model';
import type { SourceRegistryEntry } from '@data-foundry/source-registry';
import type { EditorialOverride } from '@data-foundry/canonical-store';
import { InternalTextLeak } from './errors.js';

/**
 * Every human named anywhere in the inputs to this export.
 *
 * Deliberately generous: an approver is as much a staff identity as a reviewer,
 * and a manifest is not the place for either.
 */
export function declaredReviewers(
  overrides: readonly EditorialOverride[],
  registry: readonly SourceRegistryEntry[],
): readonly string[] {
  const names = new Set<string>();
  for (const override of overrides) {
    if (typeof override.reviewer === 'string' && override.reviewer.trim() !== '') {
      names.add(override.reviewer.trim());
    }
  }
  for (const entry of registry) {
    for (const name of [entry.rights_policy.reviewed_by, entry.acquisition_policy.approved_by]) {
      if (name !== null && name.trim() !== '') names.add(name.trim());
    }
  }
  return [...names];
}

/**
 * The query-layer control, applied to each row about to be published, against
 * the full reviewer set rather than one correction's own reviewer.
 */
export function assertRowsCarryNoReviewerIdentity(
  views: readonly CanonicalFactView[],
  reviewers: readonly string[],
): void {
  if (reviewers.length === 0) return;
  for (const view of views) {
    assertNoReviewerIdentity(correctionFields(view), reviewers);
  }
}

/**
 * Sweep a serialized artifact for a full declared identity.
 *
 * Checking the bytes rather than the object is the whole point: the failure
 * mode being guarded against is a field nobody thought to check.
 *
 * A declared identity below `MIN_IDENTITY_FRAGMENT` is not searched for, for the
 * reason `MIN_INTERNAL_FRAGMENT` gives below and `reviewerIdentityTokens` gives
 * upstream: a needle that short is inside ordinary data. A rights reviewer
 * recorded by initials — `AH`, which is how a two-person legal team signs a
 * review off — is a substring of `AHRI-209876543`, a certification reference
 * this vertical publishes, and with no floor it refused every export of the
 * vertical. An over-refusal that fires on correct data does not make anything
 * safer; it gets the control switched off by whoever has to ship.
 *
 * The floor is the QUERY LAYER'S, imported rather than chosen here, and it is
 * deliberately not `MIN_INTERNAL_FRAGMENT`. Twelve characters is right for an
 * internal note, which is a sentence. Applied to a human identity it would skip
 * `m.chen` and `j.okafor` and leave this sweep armed against almost nobody,
 * which is the same control failing in the direction that actually costs
 * somebody their privacy. Two hazards, one rule each, both already written down.
 */
export function assertArtifactCarriesNoReviewerIdentity(
  path: string,
  serialized: string,
  reviewers: readonly string[],
): void {
  const haystack = serialized.toLowerCase();
  for (const reviewer of reviewers) {
    const needle = reviewer.trim().toLowerCase();
    if (needle.length < MIN_IDENTITY_FRAGMENT) continue;
    if (haystack.includes(needle)) throw new ReviewerIdentityLeak(path);
  }
}

/**
 * Text from a source declaration that is written for us, not for a customer.
 *
 * Short fragments are skipped: a four-character note is a substring of
 * everything and would refuse every export, which is the same reason
 * `reviewerIdentityTokens` declines to derive short tokens.
 */
const MIN_INTERNAL_FRAGMENT = 12;

export function internalOnlyText(registry: readonly SourceRegistryEntry[]): readonly string[] {
  const fragments = new Set<string>();
  for (const entry of registry) {
    for (const text of [
      entry.notes,
      entry.rights_policy.geographic_notes,
      entry.rights_policy.license_text_ref,
      entry.acquisition_policy.notes,
      entry.license_split.notes,
    ]) {
      if (typeof text === 'string' && text.trim().length >= MIN_INTERNAL_FRAGMENT) {
        fragments.add(text.trim());
      }
    }
  }
  return [...fragments];
}

export function assertNoInternalText(
  path: string,
  serialized: string,
  fragments: readonly string[],
): void {
  const haystack = serialized.toLowerCase();
  for (const fragment of fragments) {
    if (haystack.includes(fragment.toLowerCase())) throw new InternalTextLeak(path);
  }
}
